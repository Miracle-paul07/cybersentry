# Report rendering + one-call helper
# ---------------------------------------------------------------------------
def render_markdown(evidence, narrative, check, source):
    e, n = evidence, narrative
    lines = [
        f"# {n['title']}",
        f"**Incident ID:** {e['incident_id']}  |  **Generated:** {e['generated_at']}  |  "
        f"**Severity:** {e['severity']}  |  **Attack type:** {e['attack_type']}",
        "",
        "## Summary", n["summary"], "",
        "## Detection details",
        f"- Flows detected: **{e['flows_detected']:,}** ({e['share_of_analysed_traffic_pct']}% of analysed traffic)",
        f"- Model confidence: mean **{e['mean_confidence_pct']}%**, minimum {e['min_confidence_pct']}%",
        f"- Flows needing analyst review (confidence below threshold): {e['flows_needing_analyst_review']}",
        f"- MITRE ATT&CK: {', '.join(e['mitre_attack']) if e['mitre_attack'] else 'n/a'}",
    ]
    if e.get("top_destination_ports"):
        lines.append("- Top destination ports: " + ", ".join(f"{p['port']} ({p['flows']} flows)" for p in e["top_destination_ports"]))
    lines += ["", "## What happened", n["what_happened"], "", "## Key evidence"]
    lines += [f"- {x}" for x in n["key_evidence"]]
    lines += ["", "| Feature | Unit | Attack median | Normal median | x normal |", "|---|---|---:|---:|---:|"]
    lines += [f"| {r['feature']} | {r['unit']} | {r['attack_median']} | {r['normal_median']} | {r['times_normal'] if r['times_normal'] is not None else 'n/a'} |"
              for r in e["most_unusual_features_vs_normal"]]
    lines += ["", "## Potential impact", n["potential_impact"], "", "## Recommended actions"]
    lines += [f"{i}. {a}" for i, a in enumerate(n["recommended_actions"], 1)]
    lines += ["", "## Analyst note", n["analyst_note"], "", "---",
              f"*Narrative source: {source}. Grounding check: "
              + ("all numbers match the evidence." if check["grounded"]
                 else f"numbers not found in evidence: {', '.join(check['unsupported_numbers'])} - verify these.")
              + " CyberSentry assists analysts; it does not replace them.*"]
    return "\n".join(lines)


def generate_report(evidence, use_llm=True, model=DEFAULT_MODEL, client=None):
    """Evidence -> (markdown report, narrative dict, grounding check, source)."""
    source = "template (no LLM)"
    narrative = None
    if use_llm and (client is not None or os.environ.get("GROQ_API_KEY")):
        try:
            narrative = call_groq(evidence, model=model, client=client)
            source = f"Groq {model}"
        except Exception as e:
            print(f"[genai] LLM failed, using template: {e}")
    if narrative is None:
        narrative = template_narrative(evidence)
    check = grounding_check(narrative, evidence)
    return render_markdown(evidence, narrative, check, source), narrative, check, source
