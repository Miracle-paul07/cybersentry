def benign_baseline(df, features):
    """Median of each feature over normal (BENIGN) traffic. Computed once from training data."""
    return {f: float(df.loc[df["Label"] == "BENIGN", f].median()) for f in features}


def _fmt(x):
    x = float(x) + 0.0
    if abs(x) >= 100 or x == int(x):
        return int(round(x))
    return round(x, 2) + 0.0


def feature_unit(name):
    """Units of CICFlowMeter features (CIC-IDS2017 docs: time values are in microseconds)."""
    n = name.lower()
    if "init_win_bytes" in n:
        return "bytes (TCP window size; -1 = not available)"
    if n.endswith("/s"):
        return "bytes per second" if "bytes" in n else "packets per second"
    if "duration" in n or "iat" in n or "active" in n or "idle" in n:
        return "microseconds"
    if "length" in n or "size" in n or "bytes" in n or "seg_size" in n:
        return "bytes"
    if "flag" in n:
        return "count of flags"
    if "packets" in n or "subflow" in n or "act_data_pkt" in n:
        return "packets"
    if "ratio" in n:
        return "ratio"
    return "as recorded by CICFlowMeter"


NOT_IN_NORMAL = "not seen in normal traffic"


def _ratio_fmt(r):
    return float(f"{r:.3g}")


def build_evidence(flows, attack_type, baseline, total_flows, top_n_features=6):
    """Evidence package for one attack type, from the pipeline's output rows of that type."""
    kb = KB.get(attack_type, GENERIC_KB)
    n = len(flows)
    conf = flows["confidence"].astype(float)

    comparison = []
    for f, normal in baseline.items():
        if f not in flows.columns or f == "Destination Port":
            continue
        attack_med = float(flows[f].median())
        if abs(normal) <= 1e-9 and attack_med > 0:
            times_normal = NOT_IN_NORMAL   # a ratio against 0 is meaningless
        elif normal > 1e-9 and attack_med >= 0:
            times_normal = _ratio_fmt(attack_med / normal)
        else:
            times_normal = None
        comparison.append({"feature": f, "unit": feature_unit(f),
                           "attack_median": _fmt(attack_med), "normal_median": _fmt(normal),
                           "times_normal": times_normal,
                           # how different from normal, on a log scale; safe for 0 and -1 ("not available") values
                           "_score": abs(np.log1p(abs(attack_med)) - np.log1p(abs(normal)))})
    comparison = sorted(comparison, key=lambda r: r["_score"], reverse=True)[:top_n_features]
    for r in comparison:
        r.pop("_score")

    evidence = {
        "incident_id": f"CS-{datetime.now():%Y%m%d}-{attack_type.upper().replace(' ', '')[:10]}-{n}",
        "generated_at": f"{datetime.now():%Y-%m-%d %H:%M}",
        "attack_type": attack_type,
        "attack_description": kb["description"],
        "severity": kb["severity"],
        "mitre_attack": kb["mitre"],
        "flows_detected": int(n),
        "share_of_analysed_traffic_pct": _fmt(100 * n / max(total_flows, 1)),
        "mean_confidence_pct": _fmt(100 * conf.mean()),
        "min_confidence_pct": _fmt(100 * conf.min()),
        "flows_needing_analyst_review": int(flows["needs_review"].sum()),
        "most_unusual_features_vs_normal": comparison,
        "standard_actions": kb["actions"],
        "data_not_available": ["source/destination IP addresses", "timestamps", "packet payloads", "usernames"],
    }
    if "Destination Port" in flows.columns:
        ports = flows["Destination Port"].astype(int).value_counts().head(3)
        evidence["top_destination_ports"] = [{"port": int(p), "flows": int(c)} for p, c in ports.items()]
    return evidence


# ---------------------------------------------------------------------------
# LLM call (Groq)
# ---------------------------------------------------------------------------
NARRATIVE_SCHEMA = {
    "type": "object",
    "properties": {
        "title": {"type": "string"},
        "summary": {"type": "string"},
        "what_happened": {"type": "string"},
        "key_evidence": {"type": "array", "items": {"type": "string"}},
        "potential_impact": {"type": "string"},
        "recommended_actions": {"type": "array", "items": {"type": "string"}},
        "analyst_note": {"type": "string"},
    },
    "required": ["title", "summary", "what_happened", "key_evidence", "potential_impact",
                 "recommended_actions", "analyst_note"],
    "additionalProperties": False,
}

SYSTEM_PROMPT = """You are a SOC (security operations centre) assistant inside CyberSentry, an intrusion detection system.
You write incident explanations for a security analyst.

STRICT RULES:
- Use ONLY the facts in the EVIDENCE JSON. Never invent IP addresses, hostnames, usernames, times, CVEs, malware names or numbers.
- Every number you mention must appear in the evidence exactly as given.
- If something is not in the evidence, say it is not available rather than guessing.
- Every feature has a "unit". Always use that exact unit (e.g. microseconds), never convert or guess units.
- times_normal is attack_median / normal_median: above 1 means higher than normal, below 1 means lower than normal.
  If times_normal is the text "not seen in normal traffic", the normal median is 0: write exactly that phrase, never a ratio
  and never "not available". If times_normal is null, simply do not mention a ratio.
- Items in data_not_available do not exist in this system: never mention specific values for them, and do not ask the analyst to look them up in this report (they may check external logs).
- The detection comes from ML/DL models and may be wrong; if flows_needing_analyst_review > 0 or confidence is below 90%, say that verification is needed.
- Recommended actions must be based on standard_actions; you may adapt the wording but not add risky actions.
- Never mention JSON field names (like flows_detected or times_normal) in your text; write natural sentences instead,
  e.g. "483 times higher than normal" or "much shorter than normal traffic". Always state the unit for both values.
- Be clear and concise. Plain English, no marketing language.

Field guide: title (short), summary (2 sentences), what_happened (explain the attack in simple terms using the feature comparison),
key_evidence (3-5 bullet strings citing evidence values), potential_impact (1-2 sentences),
recommended_actions (3-5 items), analyst_note (what to verify, and the reminder that this is AI-assisted)."""


def call_groq(evidence, model=DEFAULT_MODEL, client=None, retries=3):
    """Ask the LLM to narrate the evidence. Returns a dict matching NARRATIVE_SCHEMA."""
    if client is None:
        from groq import Groq
        client = Groq(api_key=os.environ["GROQ_API_KEY"])
    messages = [{"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": "EVIDENCE:\n" + json.dumps(evidence, indent=2)}]
    last_err = None
    for attempt in range(retries):
        try:
            resp = client.chat.completions.create(
                model=model, messages=messages, temperature=0.2,
                response_format={"type": "json_schema",
                                 "json_schema": {"name": "incident_narrative", "strict": True,
                                                 "schema": NARRATIVE_SCHEMA}})
            return json.loads(resp.choices[0].message.content)
        except Exception as e:  # rate limit (429), network, or malformed output
            last_err = e
            wait = 20 if "429" in str(e) or "rate" in str(e).lower() else 2
            time.sleep(wait * (attempt + 1))
    raise RuntimeError(f"Groq call failed after {retries} attempts: {last_err}")


def template_narrative(evidence):
    """Fallback when the LLM is unavailable: same structure, filled from evidence only."""
    e = evidence
    feats = e["most_unusual_features_vs_normal"]
    ev = [f"{e['flows_detected']} flows classified as {e['attack_type']} "
          f"({e['share_of_analysed_traffic_pct']}% of analysed traffic)",
          f"Mean model confidence {e['mean_confidence_pct']}% (minimum {e['min_confidence_pct']}%)"]
    ev += [f"{r['feature']}: median {r['attack_median']} {r['unit']}, {NOT_IN_NORMAL}"
           if r["times_normal"] == NOT_IN_NORMAL else
           f"{r['feature']}: median {r['attack_median']} vs {r['normal_median']} {r['unit']} in normal traffic"
           for r in feats[:3]]
    return {
        "title": f"{e['attack_type']} activity detected",
        "summary": f"CyberSentry detected {e['flows_detected']} flows classified as {e['attack_type']}. "
                   f"Severity is rated {e['severity']}.",
        "what_happened": e["attack_description"],
        "key_evidence": ev,
        "potential_impact": "See attack description; impact depends on the targeted service.",
        "recommended_actions": e["standard_actions"],
        "analyst_note": f"{e['flows_needing_analyst_review']} flows have low confidence and need manual review. "
                        "Template report (LLM unavailable); verify against raw logs.",
    }


# ---------------------------------------------------------------------------
# Grounding check
# ---------------------------------------------------------------------------
_NUM = re.compile(r"(?<![\w.])-?\d[\d,]*(?:\.\d+)?")
_IP = re.compile(r"\b(?:\d{1,3}\.){3}\d{1,3}\b")

def _numbers_in(obj):
    nums = set()
    for m in _NUM.findall(json.dumps(obj)):
        try:
            v = float(m.replace(",", ""))
        except ValueError:
            continue
        nums.update({round(v, 2), round(v, 1), round(v)})
    return nums


def grounding_check(narrative, evidence, ignore_below=10):
    """Return numbers in the narrative that do NOT appear in the evidence (possible hallucinations).
    Small integers (< ignore_below) are ignored because they are usually list counts or wording."""
    allowed = _numbers_in(evidence)
    ev_text, nar_text = json.dumps(evidence), json.dumps(narrative)
    unsupported = [ip for ip in _IP.findall(nar_text) if ip not in ev_text]   # invented IP addresses
    for m in _NUM.findall(_IP.sub(" ", nar_text)):
        try:
            v = float(m.replace(",", ""))
        except ValueError:
            continue
        if abs(v) < ignore_below and v == int(v):
            continue
        if round(v, 2) not in allowed and round(v, 1) not in allowed and round(v) not in allowed:
            unsupported.append(m)
    return {"grounded": not unsupported, "unsupported_numbers": sorted(set(unsupported))}


